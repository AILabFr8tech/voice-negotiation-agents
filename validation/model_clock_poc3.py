"""PoC3 latency on the model's own clock, against the one the harness hears.

GPT-Live stamps every word it hears and says with `start_ms`/`end_ms` on its
own clock (`session.input_transcript.delta` and `session.output_transcript.delta`
in the census). For each measured PoC3 response:

- `model_ms`: from the end of the line's last word (`end_ms`) to the start of
  the word the measured speech begins with (`start_ms`), both on that clock. It
  is how long the model took to answer, without the inbound or outbound path.
- `model_first_ms`: the same, up to the agent's first word since the line
  started, whether filler or content (it can be negative if it started over the line).
- `rest_ms`: the measured latency (`lines.csv`) minus `model_ms`: what happens
  outside the model's clock (service input, output, network and queue).
- `last_word_ms`: from the line's end of speech to the arrival at the bridge of
  the transcript of its last word.
- `cola_ms`: how much agent audio was waiting in the queue when the text of the
  word the measured speech begins with arrived.
- `output_ms` and `delivery_ms` complete the split of the latency, together with
  `last_word_ms` and `model_ms`, into four parts that add up exactly:
  `output_ms` is how long the word the measured speech begins with took to reach
  the bridge, beyond the transcript of the last word and `model_ms`;
  `delivery_ms`, from the bridge to the harness's ear.

`model_clock_poc3_drift.csv` gives, per call, how far the model's clock ran
ahead of the computer's between the first and the last line, and how far the
service's usage counter (`session.usage.updated`), which follows the wall
clock, moved.

To know which word the measured speech begins with, the census audio deltas
are played back in sequence and in real time from their arrival time, plus the
call's typical return path: each word plays when what was already queued has
drained. The word after the line whose predicted time lies closest to the
measured onset is taken. The turn is left out if none falls within
`WINDOW_S`: the measured speech was generated by the model before hearing the line.

The model's clock is not a wall clock: over a call it runs a few seconds
ahead. Differences within a turn are comparable.

Population: the PoC3 responses with `in_the_pool = 1` in `populations.csv`.
Writes `model_clock_poc3.csv`, `model_clock_poc3_drift.csv` and
`model_clock_poc3_summary.txt` to `--output`. Reads the campaign artifacts (census, bridge JSON, harness
marks), which do not ship with the repo.

    python -m validation.model_clock_poc3
"""

from __future__ import annotations

import argparse
import csv
import json
import statistics
from pathlib import Path
from typing import Any, Final

import numpy as np

from shared.metrics import external_latency_poc3 as ext3
from shared.metrics.campaigns import CAMPAIGN_POC3
from shared.metrics.export_for_report import LOTE_DEFAULT, read_summary

RAIZ: Final[Path] = Path(__file__).resolve().parents[1]
DATA: Final[Path] = RAIZ / "docs" / "report" / "data"
# μ-law at 8 kHz: one byte per sample.
OUTPUT_SAMPLE_RATE: Final[float] = 8000.0
# Return path if the call has none measured (see `return_path`).
DEFAULT_NETWORK_S: Final[float] = 0.08
# Maximum distance between the measured onset and the predicted time of its word.
WINDOW_S: Final[float] = 1.0

COLUMNS: Final[list[str]] = [
    "clave", "turn", "scenario", "tool", "latency_ms", "model_ms",
    "model_first_ms", "rest_ms", "last_word_ms", "cola_ms", "output_ms", "delivery_ms",
]


def census_of(census_path: Path, anchor: float) -> dict[str, list[dict[str, Any]]]:
    """From the census: audio deltas, words on each side and usage counter, in epoch time."""
    audio, output, entry, usage = [], [], [], []
    for linea in census_path.read_text(encoding="utf-8").splitlines():
        if not linea.strip():
            continue
        e = json.loads(linea)
        t = anchor + float(e["t_local_seg"])
        ev = e.get("event") or {}
        if e["type"] == "session.output_audio.delta":
            bytes_ = int(str(ev.get("delta", "<audio 0 bytes>")).split()[1])
            audio.append({"arrival": t, "dur": bytes_ / OUTPUT_SAMPLE_RATE})
        elif e["type"] in ("session.output_transcript.delta", "session.input_transcript.delta"):
            word = {"arrival": t, "start": ev["start_ms"] / 1000.0, "end": ev["end_ms"] / 1000.0,
                       "text": ev.get("delta") or ""}
            (output if "output" in e["type"] else entry).append(word)
        elif e["type"] == "session.usage.updated" and (ev.get("usage") or {}).get("seconds") is not None:
            usage.append({"arrival": t, "seconds": float(ev["usage"]["seconds"])})
    return {"audio": audio, "output": output, "entry": entry, "usage": usage}


def predict(audio: list[dict[str, Any]], words: list[dict[str, Any]], network: float) -> None:
    """Time at which each agent word played, with the audio played back in sequence."""
    end = -1e18
    ends = []
    for block in audio:
        start = max(block["arrival"] + network, end)
        end = start + block["dur"]
        ends.append((block["arrival"], end))
    k, ultimo = 0, -1e18
    for p in sorted(words, key=lambda p: p["arrival"]):
        while k < len(ends) and ends[k][0] <= p["arrival"]:
            ultimo = ends[k][1]
            k += 1
        # The word's audio arrives with its text or shortly after: it plays once
        # what was already queued has drained, and never before the network allows.
        p["prevista"] = max(p["arrival"] + network, ultimo)


def return_path(rows: list[dict[str, str]]) -> float:
    """Median return path of the call, excluding those that carry a queue."""
    outbounds = [float(f["outbound_ms"]) / 1000 for f in rows if f["outbound_ms"] and float(f["outbound_ms"]) < 400]
    return statistics.median(outbounds) if outbounds else DEFAULT_NETWORK_S


def call_turns(rows: list[dict[str, str]], marks: list[dict[str, Any]],
                         census: dict[str, list[dict[str, Any]]]) -> list[dict[str, Any]]:
    marks = sorted(marks, key=lambda m: m["start_of_clip"])
    predict(census["audio"], census["output"], return_path(rows))
    output_by_start = sorted(census["output"], key=lambda p: p["start"])
    order = [str(m["turn"]) for m in marks]
    resultado = []
    for f in rows:
        if f["turn"] not in order:
            continue
        k = order.index(f["turn"])
        m = marks[k]
        tope = marks[k + 1]["start_of_clip"] if k + 1 < len(marks) else float("inf")
        linea = [p for p in census["entry"] if m["start_of_clip"] <= p["arrival"] < tope]
        if not linea:
            continue
        s_start = min(p["start"] for p in linea)
        s_end = max(p["end"] for p in linea)
        voice_end = float(m["measured_end_of_speech"])
        onset = voice_end + float(f["observed_latency_ms"]) / 1000
        subsequent = [p for p in output_by_start if p["start"] >= s_start and p["text"][:1].isspace()]
        if not subsequent:
            continue
        p = min(subsequent, key=lambda p: abs(p["prevista"] - onset))
        if abs(p["prevista"] - onset) > WINDOW_S:
            continue
        ultima = max(linea, key=lambda q: q["end"])
        model_name = (p["start"] - s_end) * 1000
        latency = float(f["observed_latency_ms"])
        ultima_ms = (ultima["arrival"] - voice_end) * 1000
        arrival_ms = (p["arrival"] - voice_end) * 1000
        resultado.append({
            "clave": f["clave"], "turn": f["turn"], "scenario": f["scenario"],
            "tool": f["tool_in_response"],
            "latency_ms": latency,
            "model_ms": round(model_name),
            "model_first_ms": round((subsequent[0]["start"] - s_end) * 1000),
            "rest_ms": round(latency - model_name, 1),
            "last_word_ms": round(ultima_ms, 1),
            "cola_ms": round((p["prevista"] - p["arrival"]) * 1000, 1),
            "output_ms": round(arrival_ms - ultima_ms - model_name, 1),
            "delivery_ms": round(latency - arrival_ms, 1),
            # Model clock minus wall clock at the end of the line; only how it
            # changes within the call matters (goes to the summary, not the CSV).
            "offset_s": s_end - voice_end,
            "wall_s": voice_end,
        })
    return resultado


def call_drift(turns: list[dict[str, Any]], usage: list[dict[str, Any]]) -> dict[str, float] | None:
    """How far the model's clock, and the usage counter, ran ahead between the first and the last line."""
    if len(turns) < 2:
        return None
    a, b = min(turns, key=lambda t: t["wall_s"]), max(turns, key=lambda t: t["wall_s"])
    # The counter rounds some updates one second up or down: the median of the
    # second half of the call is compared against that of the first half.
    offsets = [u["seconds"] - u["arrival"] for u in usage]
    half = len(offsets) // 2
    counter = statistics.median(offsets[half:]) - statistics.median(offsets[:half]) if half else float("nan")
    return {"span_s": b["wall_s"] - a["wall_s"], "model_ms": (b["offset_s"] - a["offset_s"]) * 1000,
            "usage_ms": counter * 1000}


def quartiles(values: list[float]) -> str:
    q1, q2, q3 = np.percentile(values, [25, 50, 75])
    return f"p50 {q2:,.0f}  [p25 {q1:,.0f}, p75 {q3:,.0f}]  n={len(values)}"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--data", type=Path, default=DATA)
    ap.add_argument("--lote", type=Path, default=LOTE_DEFAULT)
    ap.add_argument("--output", type=Path, default=DATA)
    args = ap.parse_args(argv)

    valid_ones = {r["clave"] for r in csv.DictReader((args.data / "populations.csv").open(encoding="utf-8"))
               if r["in_the_pool"] == "1"}
    by_key: dict[str, list[dict[str, str]]] = {}
    for f in csv.DictReader((args.data / "lines.csv").open(encoding="utf-8")):
        if f["poc"] == "3" and f["clave"] in valid_ones:
            by_key.setdefault(f["clave"], []).append(f)
    total = sum(len(v) for v in by_key.values())
    rows: list[dict[str, Any]] = []
    drifts: list[dict[str, float]] = []
    for clave, fs in sorted(by_key.items()):
        res = read_summary(args.lote / CAMPAIGN_POC3, clave) or {}
        art = res.get("artifacts") or {}
        marks = ext3.marks_de(Path(art["event_log"]).parent / f"zeros_{res['label']}.jsonl")
        live_bridge = json.loads(Path(art["bridge_json"]).read_text(encoding="utf-8"))
        census = census_of(Path(art["census"]), float(live_bridge["clock"]["anchor_wall_s"]))
        turns = call_turns(fs, marks, census)
        rows += turns
        if (d := call_drift(turns, census["usage"])) is not None:
            drifts.append({"clave": clave} | {k: round(v, 1) for k, v in d.items()})

    args.output.mkdir(parents=True, exist_ok=True)
    with (args.output / "model_clock_poc3.csv").open("w", encoding="utf-8", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=COLUMNS, extrasaction="ignore")
        w.writeheader()
        w.writerows(rows)
    with (args.output / "model_clock_poc3_drift.csv").open("w", encoding="utf-8", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=["clave", "span_s", "model_ms", "usage_ms"])
        w.writeheader()
        w.writerows(drifts)
    text_lines = [f"Respuestas de PoC3 ubicadas en el reloj del modelo: {len(rows)} de {total}."]
    for name, sub in (("all_items", rows), ("sin herramienta", [f for f in rows if f["tool"] == "0"]),
                        ("con herramienta", [f for f in rows if f["tool"] == "1"])):
        text_lines += [f"\n{name}:"] + [
            f"  {c:18s} {quartiles([float(f[c]) for f in sub])}"
            for c in ("latency_ms", "model_ms", "model_first_ms", "rest_ms", "last_word_ms", "cola_ms",
                      "output_ms", "delivery_ms")
        ]
    text_lines += [
        f"\nEntre la primera y la última línea de cada llamada ({len(drifts)} llamadas, "
        f"lapso {quartiles([d['span_s'] for d in drifts])} s):",
        f"  el reloj del modelo se adelantó   {quartiles([d['model_ms'] for d in drifts])} ms",
        f"  el contador de uso, segunda mitad contra primera {quartiles([d['usage_ms'] for d in drifts if d['usage_ms'] == d['usage_ms']])} ms",
    ]
    text = "\n".join(text_lines) + "\n"
    (args.output / "model_clock_poc3_summary.txt").write_text(text, encoding="utf-8")
    print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
